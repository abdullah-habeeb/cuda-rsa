#!/usr/bin/env python3
"""
keygen.py - Generates the RSA-2048 demo key used by the CUDA program.

Outputs
  src/rsa_key.h      C header with the key and all Montgomery constants,
                     stored as little-endian arrays of 32-bit limbs.
  results/key.json   The same key as hex strings, used by verify.py.

The key is generated deterministically from a fixed seed so that every run
of the experiment (and every figure in the report) is reproducible.
THIS IS A DEMONSTRATION KEY - never use a seeded key for real security.

Only the Python standard library is used.
"""
import json
import math
import os
import random

SEED = "1BY23CS002-RSA-CUDA-CCA"
KEY_BITS = 2048
E = 65537
LIMB_BITS = 32

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

SMALL_PRIMES = [p for p in range(3, 2000) if all(p % d for d in range(2, int(p ** 0.5) + 1))]


def is_probable_prime(n: int, rng: random.Random, rounds: int = 64) -> bool:
    """Trial division by small primes followed by Miller-Rabin."""
    if n < 2:
        return False
    for sp in SMALL_PRIMES:
        if n % sp == 0:
            return n == sp
    d, s = n - 1, 0
    while d % 2 == 0:
        d //= 2
        s += 1
    for _ in range(rounds):
        a = rng.randrange(2, n - 2)
        x = pow(a, d, n)
        if x in (1, n - 1):
            continue
        for _ in range(s - 1):
            x = pow(x, 2, n)
            if x == n - 1:
                break
        else:
            return False
    return True


def gen_prime(bits: int, rng: random.Random) -> int:
    """Random prime with the top two bits set (so p*q has exactly 2*bits bits)
    and gcd(p-1, e) = 1 (so that e is invertible)."""
    while True:
        cand = rng.getrandbits(bits) | (3 << (bits - 2)) | 1
        if math.gcd(cand - 1, E) == 1 and is_probable_prime(cand, rng):
            return cand


def to_limbs(x: int, nlimbs: int) -> list:
    assert 0 <= x < (1 << (LIMB_BITS * nlimbs))
    mask = (1 << LIMB_BITS) - 1
    return [(x >> (LIMB_BITS * i)) & mask for i in range(nlimbs)]


def c_array(name: str, x: int, nlimbs: int) -> str:
    limbs = to_limbs(x, nlimbs)
    rows = []
    for i in range(0, nlimbs, 6):
        rows.append("    " + ", ".join(f"0x{v:08x}u" for v in limbs[i:i + 6]))
    return f"static const uint32_t {name}[{nlimbs}] = {{\n" + ",\n".join(rows) + "\n};\n"


def mont_consts(m: int, nlimbs: int):
    """n0inv = -m^-1 mod 2^32 and R^2 mod m, with R = 2^(32*nlimbs)."""
    n0inv = (-pow(m, -1, 1 << LIMB_BITS)) % (1 << LIMB_BITS)
    r = 1 << (LIMB_BITS * nlimbs)
    return n0inv, (r * r) % m, r


def main():
    rng = random.Random(SEED)
    half = KEY_BITS // 2

    while True:
        p = gen_prime(half, rng)
        q = gen_prime(half, rng)
        if p == q:
            continue
        if p < q:                      # convention used by CRT: p > q, qinv = q^-1 mod p
            p, q = q, p
        n = p * q
        if n.bit_length() == KEY_BITS:
            break

    lam = (p - 1) * (q - 1) // math.gcd(p - 1, q - 1)   # Carmichael function lambda(n)
    d = pow(E, -1, lam)
    dp, dq = d % (p - 1), d % (q - 1)
    qinv = pow(q, -1, p)

    NL, HL = KEY_BITS // LIMB_BITS, half // LIMB_BITS
    n0inv, r2n, _ = mont_consts(n, NL)
    p0inv, r2p, rp = mont_consts(p, HL)
    q0inv, r2q, _ = mont_consts(q, HL)
    qinv_r = (qinv * rp) % p          # qinv in Montgomery form (mod p)

    # ---------- self-test of the key and of the CRT recombination ----------
    for _ in range(20):
        m = rng.randrange(0, n)
        c = pow(m, E, n)
        assert pow(c, d, n) == m
        m1, m2 = pow(c % p, dp, p), pow(c % q, dq, q)
        h = (qinv * (m1 - m2)) % p
        assert m2 + h * q == m
    assert (n * n0inv) % (1 << 32) == (1 << 32) - 1

    # ---------- C header ----------
    hdr = []
    hdr.append("// AUTO-GENERATED by tools/keygen.py - do not edit by hand.\n")
    hdr.append(f"// RSA-{KEY_BITS} DEMONSTRATION key (deterministic seed \"{SEED}\").\n")
    hdr.append("// All big numbers are little-endian arrays of 32-bit limbs (limb 0 = least significant).\n")
    hdr.append("#pragma once\n#include <stdint.h>\n\n")
    hdr.append(f"#define RSA_KEY_BITS {KEY_BITS}\n#define RSA_NLIMBS {NL}\n#define RSA_HLIMBS {HL}\n")
    hdr.append(f"#define RSA_E {E}u\n")
    hdr.append(f"#define RSA_E_BITS {E.bit_length()}\n")
    hdr.append(f"#define RSA_D_BITS {d.bit_length()}\n")
    hdr.append(f"#define RSA_DP_BITS {dp.bit_length()}\n")
    hdr.append(f"#define RSA_DQ_BITS {dq.bit_length()}\n")
    hdr.append(f"#define RSA_N0INV 0x{n0inv:08x}u\n#define RSA_P0INV 0x{p0inv:08x}u\n#define RSA_Q0INV 0x{q0inv:08x}u\n\n")
    hdr.append("// ---- public key (n, e) and private exponent d ----\n")
    hdr.append(c_array("RSA_N", n, NL))
    hdr.append(c_array("RSA_D", d, NL))
    hdr.append(c_array("RSA_R2N", r2n, NL) + "\n")
    hdr.append("// ---- CRT private-key components (p > q) ----\n")
    hdr.append(c_array("RSA_P", p, HL))
    hdr.append(c_array("RSA_Q", q, HL))
    hdr.append(c_array("RSA_DP", dp, HL))
    hdr.append(c_array("RSA_DQ", dq, HL))
    hdr.append(c_array("RSA_R2P", r2p, HL))
    hdr.append(c_array("RSA_R2Q", r2q, HL))
    hdr.append(c_array("RSA_QINV_R", qinv_r, HL))

    with open(os.path.join(ROOT, "src", "rsa_key.h"), "w", newline="\n") as f:
        f.write("".join(hdr))

    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    with open(os.path.join(ROOT, "results", "key.json"), "w") as f:
        json.dump({"bits": KEY_BITS, "seed": SEED, "n": hex(n), "e": E, "d": hex(d),
                   "p": hex(p), "q": hex(q), "dp": hex(dp), "dq": hex(dq), "qinv": hex(qinv)}, f, indent=2)

    print(f"RSA-{KEY_BITS} key generated (seed '{SEED}')")
    print(f"  n  : {n.bit_length()} bits  = 0x{hex(n)[2:18]}...{hex(n)[-8:]}")
    print(f"  e  : {E}")
    print(f"  d  : {d.bit_length()} bits, dp: {dp.bit_length()} bits, dq: {dq.bit_length()} bits")
    print("  self-test (20 random encrypt/decrypt + CRT round trips): PASSED")
    print("  wrote src/rsa_key.h and results/key.json")


if __name__ == "__main__":
    main()
